// Generates seed/seed.sql from data/catalogue.mjs.
//
// SAFETY GUARANTEES (production-safe, idempotent):
//  * Never deletes products, prices, history, admins or audit logs.
//  * Never overwrites a price: ProductPrices rows are INSERT OR IGNORE with a NULL price.
//  * By default products/specs/media are INSERT OR IGNORE (admin edits are preserved).
//    Pass --refresh-content to also update descriptive text/specs from the datasheet source.
//  * Marks PublishedCatalogue (a derived cache) stale so the Worker rebuilds it, keeping its version number.
//
// Usage: node scripts/generate-seed.mjs [--refresh-content] [--admin=email@example.com]

import { mkdirSync, writeFileSync } from "node:fs";
import { brands, categories, flattenProducts } from "../data/catalogue.mjs";

const args = process.argv.slice(2);
const refresh = args.includes("--refresh-content");
const adminArg = args.find((a) => a.startsWith("--admin="));
const ownerEmail = (adminArg ? adminArg.slice(8) : "Verdisolarrsolution@gmail.com").trim();

const q = (v) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const lines = [
  "-- AUTO-GENERATED by scripts/generate-seed.mjs. Do not edit by hand.",
  `-- Mode: ${refresh ? "refresh-content" : "insert-only"}. Prices are never overwritten.`,
  "PRAGMA foreign_keys = ON;",
];

for (const b of brands) {
  lines.push(
    `INSERT INTO Brands (BrandName, BrandSlug, Description) VALUES (${q(b.name)}, ${q(b.slug)}, ${q(b.description)})` +
      (refresh ? ` ON CONFLICT(BrandSlug) DO UPDATE SET BrandName = excluded.BrandName, Description = excluded.Description, UpdatedAt = strftime('%Y-%m-%dT%H:%M:%fZ','now');` : " ON CONFLICT(BrandSlug) DO NOTHING;"),
  );
}
categories.forEach((c, i) => {
  lines.push(
    `INSERT INTO Categories (CategoryName, CategorySlug, Description, SortOrder) VALUES (${q(c.name)}, ${q(c.slug)}, ${q(c.description)}, ${(i + 1) * 10})` +
      (refresh ? " ON CONFLICT(CategorySlug) DO UPDATE SET CategoryName = excluded.CategoryName, Description = excluded.Description;" : " ON CONFLICT(CategorySlug) DO NOTHING;"),
  );
});

const products = flattenProducts();
const slugs = new Set();
for (const p of products) {
  if (slugs.has(p.slug)) throw new Error(`Duplicate slug ${p.slug}`);
  slugs.add(p.slug);
  const cols = `SKU, ProductName, ProductSlug, BrandId, CategoryId, SeriesKey, SeriesName, VariantLabel, ModelNumber, ShortDescription, Description, HighlightsJson, IsFeatured`;
  const vals = `${q(p.sku)}, ${q(p.name)}, ${q(p.slug)}, (SELECT BrandId FROM Brands WHERE BrandSlug = ${q(p.brand)}), (SELECT CategoryId FROM Categories WHERE CategorySlug = ${q(p.category)}), ${q(p.seriesKey)}, ${q(p.seriesName)}, ${q(p.variant)}, ${q(p.model)}, ${q(p.short)}, ${q(p.description)}, ${q(JSON.stringify(p.highlights))}, ${p.featured ? 1 : 0}`;
  lines.push(
    `INSERT INTO Products (${cols}) VALUES (${vals})` +
      (refresh
        ? " ON CONFLICT(SKU) DO UPDATE SET ProductName = excluded.ProductName, SeriesName = excluded.SeriesName, VariantLabel = excluded.VariantLabel, ModelNumber = excluded.ModelNumber, ShortDescription = excluded.ShortDescription, Description = excluded.Description, HighlightsJson = excluded.HighlightsJson, UpdatedAt = strftime('%Y-%m-%dT%H:%M:%fZ','now');"
        : " ON CONFLICT(SKU) DO NOTHING;"),
  );
  // Price row with NULL price = "pending admin input". Never overwritten.
  lines.push(
    `INSERT OR IGNORE INTO ProductPrices (ProductId, SellingPricePaise, MRPPaise, GSTIncluded, GSTRate, PriceUnit, UpdatedBy) SELECT ProductId, NULL, NULL, 0, NULL, ${q(p.priceUnit)}, 'seed' FROM Products WHERE SKU = ${q(p.sku)};`,
  );
  for (const s of p.specs) {
    lines.push(
      `INSERT INTO ProductSpecifications (ProductId, SpecificationKey, SpecificationLabel, SpecificationValue, Unit, SpecGroup, SortOrder) SELECT ProductId, ${q(s.key)}, ${q(s.label)}, ${q(s.value)}, ${q(s.unit)}, ${q(s.group)}, ${s.sort} FROM Products WHERE SKU = ${q(p.sku)}` +
        (refresh
          ? " ON CONFLICT(ProductId, SpecificationKey) DO UPDATE SET SpecificationLabel = excluded.SpecificationLabel, SpecificationValue = excluded.SpecificationValue, Unit = excluded.Unit, SpecGroup = excluded.SpecGroup, SortOrder = excluded.SortOrder;"
          : " ON CONFLICT(ProductId, SpecificationKey) DO NOTHING;"),
    );
  }
  lines.push(
    `INSERT OR IGNORE INTO ProductMedia (ProductId, MediaType, StorageKey, Title, IsPrimary, SortOrder) SELECT ProductId, 'datasheet', ${q(p.datasheet)}, ${q(`${p.seriesName} — manufacturer datasheet`)}, 1, 0 FROM Products WHERE SKU = ${q(p.sku)};`,
  );
  p.images.forEach((img, i) =>
    lines.push(
      `INSERT OR IGNORE INTO ProductMedia (ProductId, MediaType, StorageKey, AltText, IsPrimary, SortOrder) SELECT ProductId, 'image', ${q(img.src)}, ${q(img.alt)}, ${i === 0 ? 1 : 0}, ${i} FROM Products WHERE SKU = ${q(p.sku)};`,
    ),
  );
}

lines.push(
  `INSERT OR IGNORE INTO AdminUsers (Email, DisplayName, Role) VALUES (${q(ownerEmail)}, 'Owner', 'owner');`,
  "-- Derived cache only: force the Worker to rebuild the public catalogue snapshot.",
  "-- (keeps the version number, so browsers never mistake a new copy for an old one)",
  "UPDATE PublishedCatalogue SET PayloadJson = '{}' WHERE Id = 1;",
);

mkdirSync("seed", { recursive: true });
writeFileSync("seed/seed.sql", lines.join("\n") + "\n");
console.log(`seed/seed.sql written: ${brands.length} brands, ${categories.length} categories, ${products.length} products (${refresh ? "refresh" : "insert-only"})`);
